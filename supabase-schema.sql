-- LearnWith Himanshu blog: run this in the Supabase SQL Editor.
-- Create an admin user in Supabase Authentication before enabling publishing.
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default 'Education',
  excerpt text not null,
  content text not null,
  author text not null default 'Himanshu',
  published boolean not null default false,
  created_at timestamptz not null default now(),
  read_time text
);

alter table public.posts enable row level security;

-- Anyone can read published posts; only authenticated admins may publish/edit/delete.
create policy "Public can read published posts"
on public.posts for select
using (published = true or auth.uid() is not null);

create policy "Authenticated users can publish posts"
on public.posts for insert to authenticated
with check (auth.uid() is not null);

create policy "Authenticated users can update posts"
on public.posts for update to authenticated
using (auth.uid() is not null)
with check (auth.uid() is not null);

create policy "Authenticated users can delete posts"
on public.posts for delete to authenticated
using (auth.uid() is not null);

